/**
 * Verb data for the German conjugation engine.
 *
 * Built the way the Italian file next to it is, and divided along German
 * lines rather than Romance ones. German has no conjugation classes to read
 * off the infinitive: a verb is weak, strong or mixed only because history
 * made it so, and the only way to know is to know the verb. So the data here
 * is mostly a table of principal parts, and the engine does the rest:
 *
 *   IRREGULARS           — principal parts of every strong and mixed verb, and
 *                          the full paradigms of the handful of anomalous ones
 *                          (sein, haben, werden, wissen, the modals).
 *   NOT_DERIVED          — verbs that merely look like a prefixed strong verb
 *                          (begleiten is not be + gleiten).
 *   SEPARABLE_PREFIXES   — the stressed particles that split off: stehe auf.
 *   INSEPARABLE_PREFIXES — the unstressed ones that never do, and take no ge-.
 *   DUAL_PREFIXES        — über, unter, um, durch … with a default per prefix,
 *                          and DUAL_EXCEPTIONS for the verbs that go against it.
 *   NOT_PREFIXED         — verbs that start with letters of a prefix without
 *                          being built on it (antworten, beichten, einigen).
 *   NO_GE                — the loanwords stressed late in the word, which take
 *                          no ge- in the participle the way -ieren verbs do.
 *   SEIN_VERBS           — the verbs whose compound tenses take sein.
 *   COMMON_VERBS         — the search index for the conjugator page.
 *
 * Everything a rule can produce — the weak pattern, the e-insertion after
 * -d/-t (arbeitest), the -st that merges into a sibilant (du reist), the
 * -eln/-ern verbs (ich sammle), the umlauted Konjunktiv II (kam → käme), the
 * ge- rules and the separable word order — lives in lib/conjugator-de.js.
 */

