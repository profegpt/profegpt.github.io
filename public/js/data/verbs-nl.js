/**
 * Verb data for the Dutch conjugation engine.
 *
 * Built the way the Italian file next to it is, and divided along Dutch lines:
 *
 *   IRREGULARS       — the strong verbs (principal parts), the mixed verbs
 *                      (weak past, strong participle or the reverse) and the
 *                      handful of truly anomalous verbs (zijn, hebben …).
 *   NOT_DERIVED      — verbs that merely begin like a prefixed strong verb.
 *   INSEPARABLE      — verbs whose first syllable looks like a separable
 *                      particle but is stressed as a prefix (ondernemen,
 *                      overtuigen, voorkomen), plus the few lookalikes that
 *                      are no prefix at all.
 *   NOT_PREFIXED     — verbs beginning in be-, ge-, ver- … that are not built
 *                      with that prefix (bedelen, geselen, herbergen).
 *   UNSTRESSED_ER    — polysyllabic verbs in -eren whose e is a schwa
 *                      (luisteren → luister), against the far larger loan
 *                      family in stressed -eren (studeren → studeer).
 *   STRESSED_ER      — the reverse exceptions (blokkeren → blokkeer).
 *   LONG_E           — polysyllabic verbs in -elen/-enen whose e is long.
 *   SHORT_VOWEL      — the few whose final a/o/u is short (verwelkomen).
 *   ZIJN_VERBS       — verbs whose perfect takes zijn, listed by name.
 *   ZIJN_BASES       — zijn verbs whose separable compounds keep zijn.
 *   HEBBEN_COMPOUNDS — the separable compounds that do not.
 *   COMMON_VERBS     — the search index for the conjugator page.
 *
 * Everything a rule can produce — the two weak patterns, the spelling of the
 * stem, 't kofschip, ge- and its absence after a prefix, the separable
 * particles — lives in lib/conjugator-nl.js instead.
 */

